const CHAR_WIDTH = 4;
const CHAR_HEIGHT = 5;
const CHAR_SPACING = 1;

/**
 * Calculates the width of a string rendered with the custom pixel font.
 * @param text The string to measure.
 * @param scale The rendering scale.
 * @returns The width in pixels.
 */
export const getTextWidth = (text: string, scale: number = 1): number => {
  if (!text) return 0;
  return text.length * (CHAR_WIDTH + CHAR_SPACING) * scale - (CHAR_SPACING * scale);
};

/**
 * Renders text onto a canvas context using a custom pixel font.
 * @param ctx The canvas rendering context.
 * @param text The string to draw.
 * @param x The top-left x coordinate.
 * @param y The top-left y coordinate.
 * @param color The hex color string for the text.
 * @param scale The scale multiplier for the font size.
 */
export const drawText = (
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale: number = 1
) => {
  ctx.fillStyle = color;
  let currentX = x;
  for (const char of text.toUpperCase()) {
    if (char === ' ') {
      currentX += (CHAR_WIDTH + CHAR_SPACING) * scale;
      continue;
    }
    const charData = FONT_DATA[char];
    if (charData) {
      for (let r = 0; r < CHAR_HEIGHT; r++) {
        for (let c = 0; c < CHAR_WIDTH; c++) {
          if (charData[r][c] === 1) {
            ctx.fillRect(
              Math.floor(currentX + c * scale),
              Math.floor(y + r * scale),
              scale,
              scale
            );
          }
        }
      }
    }
    currentX += (CHAR_WIDTH + CHAR_SPACING) * scale;
  }
};
