const CHAR_WIDTH = 8;
const CHAR_HEIGHT = 8;
const CHAR_SPACING = 0; // DOS fonts are typically monospace with no extra spacing

/**
 * Calculates the width of a string rendered with the custom DOS pixel font.
 * @param text The string to measure.
 * @returns The width in pixels.
 */
export const getDosTextWidth = (text: string): number => {
  if (!text) return 0;
  return text.length * (CHAR_WIDTH + CHAR_SPACING) - CHAR_SPACING;
};

/**
 * Renders text onto a canvas context using a custom DOS pixel font.
 * @param ctx The canvas rendering context.
 * @param text The string to draw.
 * @param x The top-left x coordinate.
 * @param y The top-left y coordinate.
 * @param color The hex color string for the text.
 */
export const drawDosText = (
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string
) => {
  ctx.fillStyle = color;
  let currentX = x;
  for (const char of text.toUpperCase()) {
    if (char === ' ') {
      currentX += (CHAR_WIDTH + CHAR_SPACING);
      continue;
    }
    const charData = DOS_FONT_DATA[char];
    if (charData) {
      for (let r = 0; r < CHAR_HEIGHT; r++) {
        for (let c = 0; c < CHAR_WIDTH; c++) {
          if (charData[r][c] === 1) {
            ctx.fillRect(
              Math.floor(currentX + c),
              Math.floor(y + r),
              1,
              1
            );
          }
        }
      }
    }
    currentX += (CHAR_WIDTH + CHAR_SPACING);
  }
};
